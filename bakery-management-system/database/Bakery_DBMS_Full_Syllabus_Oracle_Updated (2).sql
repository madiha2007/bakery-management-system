-- 1. CREATE TABLES (DDL) AND INTEGRITY CONSTRAINTS
-- Create parent tables before tables that reference them.
------------------------------------------------------------

CREATE TABLE Customers (
    CustomerID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FirstName  VARCHAR2(50) NOT NULL,
    LastName   VARCHAR2(50) NOT NULL,
    Email      VARCHAR2(100) UNIQUE
);

CREATE TABLE Products (
    ProductID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductName VARCHAR2(100) NOT NULL,
    Price       NUMBER(10,2) CHECK (Price >= 0)
);

CREATE TABLE Categories (
    CategoryID   NUMBER PRIMARY KEY,
    CategoryName VARCHAR2(100) UNIQUE NOT NULL
);

-- Use explicit OrderID values 17-31 to match the Payments examples in the PDF.
CREATE TABLE Orders (
    OrderID    NUMBER PRIMARY KEY,
    OrderDate  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CustomerID NUMBER NOT NULL,
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerID)
);

CREATE TABLE Payments (
    PaymentID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OrderID       NUMBER NOT NULL,
    PaymentDate   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Amount        NUMBER(10,2) CHECK (Amount >= 0),
    PaymentMethod VARCHAR2(50),
    CONSTRAINT fk_payments_order
        FOREIGN KEY (OrderID) REFERENCES Orders(OrderID)
);

CREATE TABLE Reviews (
    ReviewID   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProductID  NUMBER NOT NULL,
    CustomerID NUMBER NOT NULL,
    ReviewText CLOB,
    Rating     NUMBER CHECK (Rating BETWEEN 1 AND 5),
    ReviewDate TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_review_product_customer UNIQUE (ProductID, CustomerID),
    CONSTRAINT fk_reviews_product FOREIGN KEY (ProductID) REFERENCES Products(ProductID),
    CONSTRAINT fk_reviews_customer FOREIGN KEY (CustomerID) REFERENCES Customers(CustomerID)
);


-- Products whose price is above the average price of their own price group.
SELECT p.ProductID, p.ProductName, p.Price
FROM Products p
WHERE p.Price > (
    SELECT AVG(p2.Price)
    FROM Products p2
    WHERE CASE WHEN p2.Price < 10 THEN 'Low'
               WHEN p2.Price <= 20 THEN 'Medium'
               ELSE 'High' END
        = CASE WHEN p.Price < 10 THEN 'Low'
               WHEN p.Price <= 20 THEN 'Medium'
               ELSE 'High' END
)
ORDER BY p.Price DESC;

-- Categories and product counts through the many-to-many mapping table.
SELECT c.CategoryID, c.CategoryName,
       COUNT(pcm.ProductID) AS ProductCount
FROM Categories c
LEFT JOIN ProductCategoryMap pcm ON pcm.CategoryID = c.CategoryID
GROUP BY c.CategoryID, c.CategoryName
ORDER BY ProductCount DESC, c.CategoryName;


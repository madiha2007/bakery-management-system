CREATE OR REPLACE FUNCTION GetAverageProductRating (
    p_ProductID IN NUMBER
) RETURN NUMBER IS
    v_AverageRating NUMBER(4,2);
BEGIN
    SELECT NVL(AVG(Rating), 0)
    INTO v_AverageRating
    FROM Reviews
    WHERE ProductID = p_ProductID;


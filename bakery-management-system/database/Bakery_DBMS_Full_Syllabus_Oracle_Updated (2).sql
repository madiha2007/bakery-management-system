-- 27. TRANSACTIONS, LOCKS AND RECOVERY: PRACTICAL DEMOS / THEORY NOTES
------------------------------------------------------------
-- ACID:
-- Atomicity = all transaction operations succeed or none do.
-- Consistency = constraints remain satisfied.
-- Isolation = concurrent transactions do not interfere improperly.
-- Durability = committed changes persist.
--
-- Transaction state path (conceptual): Active -> Partially Committed -> Committed.
-- On an error, a transaction may go Active -> Failed -> Aborted.
-- Concurrent execution interleaves operations from multiple transactions.
-- Conflict serializability is tested using a precedence graph; a cycle means the
-- schedule is not conflict-serializable. View serializability preserves reads-from
-- relationships and final writes.
--
-- Lock-based protocol example: SELECT ... FOR UPDATE locks selected rows until
-- COMMIT or ROLLBACK. Run this demo in a test session, then COMMIT to release locks.
SELECT ProductID, ProductName, Price
FROM Products
WHERE ProductID = 1
FOR UPDATE;
COMMIT;

-- Deadlock: T1 holds resource A and waits for B while T2 holds B and waits for A.
-- Handling may involve detection and rollback of a victim transaction, prevention,
-- avoidance or timeout. Timestamp protocols order conflicting operations by timestamps.
-- Recovery theory: failures include transaction, system/crash and media failures.
-- Log-based recovery records changes for undo/redo; write-ahead logging writes log
-- records before changed pages. Shadow paging keeps old pages and redirects updates.
-- Oracle implements internal recovery mechanisms; these notes are syllabus concepts,
-- not commands that implement a complete recovery system.


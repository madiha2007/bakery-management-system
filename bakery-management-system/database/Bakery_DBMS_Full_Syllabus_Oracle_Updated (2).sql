-- 26. NORMALIZATION STUDY NOTES (THEORY; READ, DO NOT EXECUTE)
------------------------------------------------------------
-- Design guidelines:
-- 1. Give each table one clear subject/entity.
-- 2. Choose a primary key that uniquely identifies each row.
-- 3. Store each fact once and avoid repeating groups.
-- 4. Use foreign keys to represent relationships and preserve referential integrity.
-- 5. Avoid update, insertion and deletion anomalies.
--
-- Functional dependency example: CustomerID -> FirstName, LastName, Email.
-- This means a CustomerID determines that customer's name and email.
--
-- 1NF: each field contains one atomic value; no repeating groups.
-- 2NF: in 1NF and every non-key attribute depends on the whole candidate key,
--      not just part of a composite key.
-- 3NF: in 2NF and no non-key attribute depends transitively on a candidate key.
-- BCNF: for every non-trivial FD X -> Y, X must be a superkey.
-- 4NF: no non-trivial multivalued dependency unless its determinant is a superkey.
-- 5NF: join dependencies are implied by candidate keys; decomposition avoids spurious
--      tuples and can be losslessly reconstructed.
--
-- Bakery design example: Customers, Products, Orders, Payments, Reviews and
-- Categories are separated by subject. ProductCategoryMap resolves the many-to-many
-- relationship between Products and Categories. The PK/FK constraints enforce keys.
-- To demonstrate 1NF-to-5NF fully in an assignment, show a raw relation, list its FDs,
-- identify anomalies, and show each decomposition step with sample rows.


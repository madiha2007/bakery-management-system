-- 31H. NORMALIZATION SUMMARY (FOR EXAM REVISION)
------------------------------------------------------------
-- UNF: repeating groups / non-atomic lists may be present.
-- 1NF: every attribute value is atomic; no repeating groups.
-- 2NF: 1NF + no partial dependency of a non-prime attribute on part of a candidate key.
-- 3NF: 2NF + no transitive dependency of non-key attributes on a candidate key.
-- BCNF: every determinant in every non-trivial FD is a superkey.
-- 4NF: no non-trivial multivalued dependency unless its determinant is a superkey.
-- 5NF: every non-trivial join dependency is implied by candidate keys.
-- Benefits: reduces duplicate data and insertion, update and deletion anomalies.
-- Remember: normalization is a design process; SQL creates the resulting tables,
-- but the normal form must be justified using keys, functional dependencies and
-- multivalued/join dependencies. These examples are for practice, not a formal proof
-- that every real-world bakery relation satisfies every normal form.


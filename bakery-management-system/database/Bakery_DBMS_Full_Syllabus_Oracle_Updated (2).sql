-- 14. FUNCTION FROM THE PDF: PLACE AN ORDER AND RETURN ITS ID
-- Uses Seq_Orders.NEXTVAL to generate a new OrderID.
------------------------------------------------------------

CREATE OR REPLACE FUNCTION PlaceOrder (
    p_CustomerID IN NUMBER
) RETURN NUMBER IS
    v_OrderID NUMBER;
BEGIN
    SELECT Seq_Orders.NEXTVAL
    INTO v_OrderID
    FROM DUAL;

    INSERT INTO Orders (OrderID, OrderDate, CustomerID)
    VALUES (v_OrderID, CURRENT_TIMESTAMP, p_CustomerID);

    RETURN v_OrderID;
END PlaceOrder;
/

DECLARE
    v_OrderID NUMBER;
BEGIN
    v_OrderID := PlaceOrder(1);
    DBMS_OUTPUT.PUT_LINE('New Order ID: ' || v_OrderID);
END;
/

-- Demonstrate NEXTVAL directly. This consumes another sequence number.
SELECT Seq_Orders.NEXTVAL AS NewOrderID FROM DUAL;


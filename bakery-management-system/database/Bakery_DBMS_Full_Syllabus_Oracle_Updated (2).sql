-- 28. MODULE 1 AND MODULE 2 THEORY / RELATIONAL ALGEBRA NOTES
------------------------------------------------------------
-- Database: organized related data managed by a DBMS.
-- Characteristics: controlled redundancy, integrity, security, sharing, backup/recovery.
-- File system vs DBMS: file systems often duplicate data and have weaker centralized
-- constraints/concurrency; DBMS provides schemas, queries, constraints and transactions.
-- Data abstraction: physical, logical and view levels.
-- Data independence: physical changes need not change the logical schema; logical
-- changes should have minimal impact on user views/programs.
-- DBMS architecture: commonly described using external, conceptual and internal levels;
-- deployment may be 1-tier, 2-tier or 3-tier. DBA manages security, backup, performance,
-- schema, access and recovery. Database types include relational, document, key-value,
-- column-family, graph, hierarchical, network and object-oriented.
--
-- ER/EER concepts: strong entity has its own key; weak entity depends on an owner entity.
-- Attributes may be simple/composite, single/multivalued, stored/derived and key attributes.
-- Cardinality: 1:1, 1:N, N:1, M:N. Participation: total or partial.
-- Generalization combines lower-level entities into a supertype; specialization divides
-- a supertype into subtypes; aggregation treats a relationship as a higher-level unit.
-- Mapping: strong entity -> table; weak entity -> table including owner's key; 1:N -> FK
-- on N-side; M:N -> bridge table with both FKs; multivalued attribute -> separate table.
--
-- Relational algebra operators:
-- Unary: selection σ (filter rows), projection π (choose columns), rename ρ.
-- Binary: union ∪, set difference −, intersection ∩, Cartesian product ×, join ⋈.
-- Equivalent SQL examples in this script include WHERE (selection), SELECT columns
-- (projection), UNION/INTERSECT/MINUS (set operators), CROSS JOIN and JOIN.
-- Example algebra: σ Price > 20 (Products) corresponds to:
-- SELECT * FROM Products WHERE Price > 20;
-- Example algebra: π ProductName,Price (Products) corresponds to:
-- SELECT ProductName, Price FROM Products;


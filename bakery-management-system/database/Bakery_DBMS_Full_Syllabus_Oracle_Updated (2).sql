CREATE OR REPLACE TRIGGER trg_AfterPaymentInsert
AFTER INSERT ON Payments
FOR EACH ROW
BEGIN
    INSERT INTO PaymentLog (PaymentID, OrderID, PaymentDate, Amount, PaymentMethod)
    VALUES (:NEW.PaymentID, :NEW.OrderID, :NEW.PaymentDate, :NEW.Amount, :NEW.PaymentMethod);
END trg_AfterPaymentInsert;
